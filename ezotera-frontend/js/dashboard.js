    // ── Logout ────────────────────────────────────────────────────────────────
    function handleLogout() {
        try { localStorage.removeItem('ezotera_onboarding'); } catch (e) {}
        fetch('/api/auth/logout', {
            method: 'POST',
            credentials: 'include'
        })
        .then(function(response) {
            return response.json();
        })
        .then(function() {
            window.location.href = '/';
        })
        .catch(function(err) {
            console.error('Logout error:', err);
            window.location.href = '/';
        });
    }

